"""Fleet maintenance instance of Section 5 (Figure 2).

Every machine is a constituent MDP with nine states and two actions:

* states 1-7 (indices 0-6): age of a working machine, 1 = as new;
* state 8 (index 7): failed, absorbing under both actions;
* state 9 (index 8): repair phase, returns to the as-new state 1 in the next period.

Under `do nothing` (action 0), a working machine of age s ages by one level and suffers a shock failure with
probability theta * (s - 1), theta = 0.04; a machine of age 7 keeps its age until it fails (probability 0.24).
Under `repair` (action 1), a working machine enters the repair phase; repairing a failed machine or a machine in the
repair phase uses capacity without effect. Rewards (do nothing / repair): working 0.6 / 0.45, failed 0.1 / 0,
repair phase 0.3 / 0. The initial state is uniformly distributed, and `repair` consumes one unit of the single
resource, of which beta * I units are available per period (the repair ratio beta).

The decision maker knows the rewards and the supports of the transition probabilities (``mask``), not the
probabilities themselves. Only the `do nothing` rows of the ages 2-7 have two reachable successor states.
"""
import numpy as np

# Section 5: I = 100 machines, T = 30 periods, K trajectories of length ell = 15 per machine, generated by a
# historical policy that repairs with probability 0.3 in every state and period.
N_MACHINES = 100
HORIZON = 30
TRAJECTORY_LENGTH = 15
BEHAVIOR_REPAIR_PROB = 0.3

N_AGES = 7
SHOCK_RATE = 0.04          # theta: shock failure probability theta * (s - 1) at age s
REPAIR_PHASE_REWARD = 0.3  # reward of the repair state under `do nothing`
DO_NOTHING, REPAIR = 0, 1
FAILED, REPAIR_PHASE = N_AGES, N_AGES + 1   # 0-based indices of states 8 and 9
N_STATES, N_ACTIONS = N_AGES + 2, 2


def machine_model(n=N_AGES, delta=SHOCK_RATE, r_minor=REPAIR_PHASE_REWARD):
    """True kernel p0 (S, A, S'), rewards r (S, A), support mask (S, A, S') and initial distribution q (S,) of one machine."""
    S = n + 2
    P = np.zeros((S, 2, S))
    B, M = n, n + 1                                 # failed state, repair phase
    P[0, 0, 1] = 1.0                                # as new: ages, no shock
    for s in range(1, n - 1):                       # ages 2..6 (1-based): age or shock failure w.p. delta * (age - 1)
        P[s, 0, s + 1] = 1 - delta * s
        P[s, 0, B] = delta * s
    f = delta * (n - 1)                             # oldest age: keeps its age until it fails
    P[n - 1, 0, n - 1] = 1 - f
    P[n - 1, 0, B] = f
    P[:n, 1, M] = 1.0                               # repair of a working machine: repair phase
    P[B, 0, B] = 1.0                                # a failure is final within the horizon
    P[B, 1, B] = 1.0
    P[M, 0, 0] = 1.0                                # repair phase: back to as new
    P[M, 1, M] = 1.0                                # repairing again: stays in the repair phase
    R = np.zeros((S, 2))
    R[:n] = 0.6, 0.45
    R[B] = 0.1, 0.0
    R[M] = r_minor, max(r_minor - 0.3, 0.0)
    return P, R, P > 0, np.full(S, 1 / S)


def fleet(n_machines=N_MACHINES):
    """True kernel (I, S, A, S'), rewards (S, A), support mask (I, S, A, S') and initial distributions (I, S) of the fleet."""
    P1, R, mask1, q1 = machine_model()
    S = P1.shape[0]
    P0 = np.broadcast_to(P1, (n_machines, S, 2, S)).copy()
    mask = np.broadcast_to(mask1, P0.shape)
    q = np.broadcast_to(q1, (n_machines, S)).copy()
    return P0, R, mask, q


def repair_capacity(beta, n_machines=N_MACHINES):
    """Budget b_t = beta * I as an integer number of repairs per period (robust to floating point error)."""
    return int(np.floor(beta * n_machines + 1e-9))
